/**
 * `trunk clone <url> [dir]`: the full path from a remote URL to a configured,
 * committed project. Every other command is a variation of this pipeline.
 *
 * Two rules shape the code. Nothing ever changes directory: every git call
 * carries `--git-dir` or `-C`, so the pipeline is safe to run from inside
 * another worktree. And every step records what it is about to create in the
 * journal before acting, so an interrupted run can describe or undo precisely
 * what exists.
 */
